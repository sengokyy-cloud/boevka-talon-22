/* Pacing order for the illustrated cutaways. Paths are local, no tracking. */
(() => {
 const pair = id => [1,2,3].map(n => 'art/sequences/'+id+'-0'+n+'.webp');
 const nature = n => 'art/nature/'+n+'.webp';
 const stills = {
   '01': 'Ты и Паша в бумажном прокате у жёлтой вывески. На столе синяя защита и талон.',
   '02': 'Ты отталкиваешься на роликах, ветер поднимает талон над аллеей.',
   '03': 'Пешеходный мост над Тускарью. Талон летит к дальнему берегу.',
   '04': 'Бумажные домики кофейни. На стойке мороженое.',
   '05': 'Бумажные кролики у забора мини-фермы и талон на земле.',
   '06': 'Ты на качелях. Через деревья виден лежак у реки.',
   '07': 'Ты отдыхаешь у воды с мороженым. На лежаке талон.',
   '08': 'С вечернего моста видно отражение деревьев и золотого светлячка.',
   '09': 'Закрытая будка со светом фонаря, конвертом и возвращёнными роликами.',
   '10': 'Открытая тетрадь в клетку. Слева бумажная Боевка, справа поздравление.'
 };
 const titles = { '01':'Защита и первый толчок', '02':'Талон над аллеей', '03':'Другой берег', '04':'От кофейни к кроликам', '05':'Талон снова в воздухе', '06':'Качели и берег', '07':'Вечер над Тускарью', '08':'За светлячком', '09':'Конверт и тетрадь' };
 function sequence(id, choice=''){
   const f = pair(id);
   if(id==='02') f.splice(1,0,nature('grove'));
   if(id==='04'){
      if(/дыневое/i.test(choice)) f[0]='art/sequences/04-melon.webp';
      f[1]='art/sequences/04-awning.webp';
   }
   if(id==='07') f.splice(1,0,nature('river'));
   if(id==='08') f.splice(2,0,nature('lantern'));
   if(id==='09') {
     f.splice(2,1,'art/sequences/09-turn.webp');
     f.push('art/sequences/09-rise.webp');
     f.unshift(nature('birch'));
   }
   return f;
 }
 window.Shots = { sequence, titles, stills };
})();
